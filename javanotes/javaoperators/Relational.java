package javaoperators;

//{ > , < , <= , >= , == , != }
// true or flase
//uses atleast 2 variable

public class Relational {
    public static void main( String [] args){ 
        int a = 10;
        int b = 5;

        System.out.println("a>b: " + (a>b));
        System.out.println("a<b: " + (a<b));
        System.out.println("a<=b: " + (a<=b));
        System.out.println("a>=b: " + (a>=b));
        System.out.println("a==b: " + (a==b)); 
        System.out.println("a!=b: "+ (a!=b));
    }
}
